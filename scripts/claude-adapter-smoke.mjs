import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {handle} from '../Resources/ClaudeAdapter/adapter.mjs';
const sdk=await import(pathToFileURL(process.argv[2]).href);
const id='11111111-1111-4111-8111-111111111111';
const dir='/tmp/blink-synthetic-sdk-only';
const rows=Array.from({length:205},(_,i)=>({type:i%2?'assistant':'user',uuid:`00000000-0000-4000-8000-${String(i).padStart(12,'0')}`,parentUuid:i?`00000000-0000-4000-8000-${String(i-1).padStart(12,'0')}`:null,sessionId:id,cwd:dir,timestamp:new Date(1700000000000+i).toISOString(),message:{role:i%2?'assistant':'user',content:[{type:'text',text:i===204?'BLINK-SDK-FINAL-PAGE':'Synthetic message '+i}]}}));
const store={append:async()=>{throw Error('Write forbidden')},load:async()=>rows,listSessions:async()=>[{sessionId:id,mtime:1700000000204}]};
const actual={listSessions:o=>sdk.listSessions({...o,sessionStore:store}),getSessionInfo:(id,o)=>sdk.getSessionInfo(id,{...o,sessionStore:store}),getSessionMessages:(id,o)=>sdk.getSessionMessages(id,{...o,sessionStore:store})};
const listed=await handle(actual,{action:'list',dir});
assert.equal(listed.sessions.length,1); assert.equal(listed.sessions[0].sessionId,id);
const result=await handle(actual,{action:'read',id,dir});
const archive=JSON.parse(result.archive);
assert.equal(archive.messages.length,205);assert.match(result.archive,/BLINK-SDK-FINAL-PAGE/);assert.equal(result.partial,true);assert.equal(archive.apiChainExhausted,true);
console.log('PASS official SDK SessionStore list/read: 205 ordered messages across 3 pages, final marker and explicit preservation limits');
const changing={...actual,getSessionInfo:async()=>({sessionId:id,summary:'synthetic',cwd:dir,lastModified:Math.random(),fileSize:1})};
await assert.rejects(handle(changing,{action:'read',id,dir}),/Source changed/);
console.log('PASS source mutation rejects capture');
const repeating={...actual,getSessionMessages:async()=>Array.from({length:100},()=>({uuid:'same'}))};
await assert.rejects(handle(repeating,{action:'read',id,dir}),/Unstable pagination/);
console.log('PASS repeated item pagination rejected');
const fifty={...actual,listSessions:async()=>Array.from({length:50},()=>({sessionId:id,summary:'synthetic',lastModified:1}))};
assert.equal((await handle(fifty,{action:'list',offset:50})).nextOffset,100);
console.log('PASS metadata list pagination continues');
const wrongID={...actual,getSessionInfo:async()=>({sessionId:'22222222-2222-4222-8222-222222222222',cwd:dir,lastModified:1})};
await assert.rejects(handle(wrongID,{action:'read',id,dir}),/identity mismatch/);
console.log('PASS mismatched session identity rejected');
await assert.rejects(handle(actual,{action:'read',id,dir:'/tmp/wrong-project'}),/Project mismatch/);
console.log('PASS wrong project rejected');
await assert.rejects(handle({...actual,getSessionMessages:async()=>[]},{action:'read',id,dir}),/No readable messages/);
console.log('PASS empty history rejected');
const long={...actual,getSessionMessages:async(_id,o)=>Array.from({length:100},(_,i)=>({uuid:'item-'+(o.offset+i),type:'user',message:{content:'synthetic'}}))};
const capped=JSON.parse((await handle(long,{action:'read',id,dir})).archive);
assert.equal(capped.messages.length,10000);assert.equal(capped.apiChainExhausted,false);
console.log('PASS long history stops at 10000 messages with explicit incomplete chain');
await assert.rejects(handle({...actual,getSessionMessages:async()=>[{uuid:'large',message:'x'.repeat(33*1024*1024)}]},{action:'read',id,dir}),/capture size/);
console.log('PASS oversized history rejected before transfer');
const unicode={...actual,getSessionInfo:async()=>({...await actual.getSessionInfo(id,{dir}),cwd:'/tmp/caf\u00e9'})};
assert.ok((await handle(unicode,{action:'read',id,dir:'/tmp/cafe\u0301'})).archive);
console.log('PASS equivalent Unicode project paths accepted without accepting a different project');
